    # 2단계: 세 묶음(세 다리)으로 묶은 디두흐
    legs = ''
    for (x0, x1) in [(cx - 20, cx - 44), (cx, cx), (cx + 20, cx + 44)]:
        for _ in range(9):
            j = R.uniform(-7, 7)
            legs += f'<line x1="{x0 + j * .6:.1f}" y1="226" x2="{x1 + j:.1f}" y2="322" stroke="{R.choice(["#d9b35a", "#c99c44", "#e6c46e"])}" stroke-width="2.2"/>'
