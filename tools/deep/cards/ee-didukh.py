    for k in range(26):
        ang = -78 + 156 * k / 25 + R.uniform(-4, 4)
        a = math.radians(ang)
        x0, y0 = cx + math.sin(a) * 10, 150 - math.cos(a) * 6
        L = 34 + R.uniform(0, 26) * math.cos(a)
