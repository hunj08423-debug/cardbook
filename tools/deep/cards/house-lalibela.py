# ---------- 만드는 차례 그림(이 안내서가 그림) ----------
# 앞쪽 바위를 잘라 내고 속을 비스듬히 내려다본 그림(등각 투영). 단위는 m, 크기는 BAS·월드 아키올로지를 어림해 씀.
# data-s="n": n단계에 나타남, data-off="n": n단계에 사라짐.
# 0 평평한 바위 → 1 둘레 그리기 → 2 둘레 파기(약 4m) → 3 마당 바닥까지(약 11m, 계단 단)
# → 4 창·문·가짜 창 새기기 → 5 안 파내기(위 창과 문이 뚫림, 가짜 창은 그대로) → 6 물 빠지는 도랑과 들어가는 길
_C30, _S30, _K = math.cos(math.pi / 6), 0.5, 7.6
_L, _A = 28.5, 6.5                 # 바위 판 0~L, 마당 A~L(약 22m)
_OX, _OY = _L * _C30 * _K + 8, 12.0
_DEP, _SLAB = 11.0, 12.6           # 마당 깊이(약 11m), 판 두께
_CX = _CY = (_A + _L) / 2
_W, _E = 2.3, 6.2                  # 십자 팔 반너비, 반길이
_PL = [(1.5, 0.6), (1.0, 0.6), (0.5, 0.6)]   # 계단 단(바깥으로 넓힘, 높이) 아래부터
_ZB = -_DEP + sum(h for _, h in _PL)
_TOP, _TOPC, _FLOOR = '#c9977c', '#cf9f84', '#b98469'
_FX, _FY = '#a9715a', '#8f5a46'    # +x를 보는 면(밝게), +y를 보는 면(어둡게)
_WX, _WY = '#9a6450', '#82513f'    # 마당 벽
_CUTX, _CUTY = '#b07a63', '#97624e'  # 잘라 낸 단면
_EDGE = 'stroke="rgba(55,28,18,.38)" stroke-width=".7" stroke-linejoin="round"'
_HOLE = '#2a1912'
_RELIEF = 'rgba(70,34,22,.30)'

def _P(x, y, z):
    return (_OX + (x - y) * _C30 * _K, _OY + ((x + y) * _S30 - z) * _K)

def _pts(pts):
    return ' '.join(f'{a:.1f},{b:.1f}' for a, b in (_P(*p) for p in pts))

def _poly(pts, fill, extra=''):
    return f'<polygon points="{_pts(pts)}" fill="{fill}" {_EDGE}{extra}/>'

def _cross(w, e, cx=_CX, cy=_CY):
    return [(cx - w, cy - e), (cx + w, cy - e), (cx + w, cy - w), (cx + e, cy - w), (cx + e, cy + w), (cx + w, cy + w),
            (cx + w, cy + e), (cx - w, cy + e), (cx - w, cy + w), (cx - e, cy + w), (cx - e, cy - w), (cx - w, cy - w)]

def _inside(fp, x, y):
    c = False
    for i in range(len(fp)):
        (x1, y1), (x2, y2) = fp[i], fp[(i + 1) % len(fp)]
        if (y1 > y) != (y2 > y) and x < x1 + (y - y1) / (y2 - y1) * (x2 - x1):
            c = not c
    return c

def _faces(fp, z0, z1):
    """보이는 옆면(+x, +y 쪽)을 뒤에서 앞 차례로"""
    out = []
    for i in range(len(fp)):
        (x1, y1), (x2, y2) = fp[i], fp[(i + 1) % len(fp)]
        q = [(x1, y1, z1), (x2, y2, z1), (x2, y2, z0), (x1, y1, z0)]
        if x1 == x2:
            if not _inside(fp, x1 + .01, (y1 + y2) / 2):
                out.append((x1 + (y1 + y2) / 2, q, _FX, ('x', x1, min(y1, y2), max(y1, y2))))
        elif not _inside(fp, (x1 + x2) / 2, y1 + .01):
            out.append(((x1 + x2) / 2 + y1, q, _FY, ('y', y1, min(x1, x2), max(x1, x2))))
    return sorted(out, key=lambda t: t[0])

def _on(info, u, z):
    kind, k, a, b = info
    return (k, a + u, z) if kind == 'x' else (a + u, k, z)

def _fpoly(info, pts2d, fill):
    return _poly([_on(info, u, z) for u, z in pts2d], fill)

def _arch(uc, z0, wd, ht):
    h = wd / 2
    return [(uc - h, z0), (uc + h, z0), (uc + h, z0 + ht), (uc + h * .7, z0 + ht + h * .55), (uc, z0 + ht + h * .8), (uc - h * .7, z0 + ht + h * .55), (uc - h, z0 + ht)]

def _rect(uc, z0, wd, ht):
    return [(uc - wd / 2, z0), (uc + wd / 2, z0), (uc + wd / 2, z0 + ht), (uc - wd / 2, z0 + ht)]

def _deco(info):
    """면마다: 위에 창 하나와 십자 돋을새김(4단계), 아래는 끝면이면 문·옆면이면 가짜 창. 5단계에 위 창과 문이 뚫림"""
    kind, k, a, b = info
    uc = (b - a) / 2
    tip = abs(k - (_CX + _E)) < 1e-6 or abs(k - (_CY + _E)) < 1e-6
    s = '<g data-s="4">' + _fpoly(info, _arch(uc, -3.9, .9, 1.5), _RELIEF)
    s += _fpoly(info, _rect(uc, -1.95, .16, .7), 'rgba(70,34,22,.55)') + _fpoly(info, _rect(uc, -1.72, .55, .16), 'rgba(70,34,22,.55)')
    if tip:
        s += _fpoly(info, _rect(uc, _ZB, 1.6, 3.0), 'rgba(70,34,22,.22)') + _fpoly(info, _rect(uc, _ZB, 1.1, 2.6), _RELIEF)
    else:
        s += _fpoly(info, _rect(uc, _ZB + 1.3, 1.1, 1.5), 'rgba(70,34,22,.22)') + _fpoly(info, _rect(uc, _ZB + 1.45, .75, 1.2), _RELIEF)
    s += '</g><g data-s="5">' + _fpoly(info, _arch(uc, -3.75, .62, 1.3), _HOLE)
    if tip:
        s += _fpoly(info, _rect(uc, _ZB, 1.1, 2.6), _HOLE)
    return s + '</g>'

def _prism(fp, z0, z1, deco=None):
    s = ''
    for _, q, col, info in _faces(fp, z0, z1):
        s += _poly(q, col) + (deco(info) if deco else '')
    return s + _poly([(x, y, z1) for x, y in fp], _TOPC)

def _pit(d):
    L, A = _L, _A
    s = _poly([(L, 0, 0), (L, A, 0), (L, A, -_SLAB), (L, 0, -_SLAB)], _CUTX) + _poly([(0, L, 0), (A, L, 0), (A, L, -_SLAB), (0, L, -_SLAB)], _CUTY)
    s += _poly([(L, A, -d), (L, L, -d), (L, L, -_SLAB), (L, A, -_SLAB)], _CUTX) + _poly([(A, L, -d), (L, L, -d), (L, L, -_SLAB), (A, L, -_SLAB)], _CUTY)
    s += _poly([(0, 0, 0), (L, 0, 0), (L, A, 0), (A, A, 0), (A, L, 0), (0, L, 0)], _TOP)
    s += _poly([(A, A, 0), (A, L, 0), (A, L, -d), (A, A, -d)], _WX) + _poly([(A, A, 0), (L, A, 0), (L, A, -d), (A, A, -d)], _WY)
    return s + _poly([(A, A, -d), (L, A, -d), (L, L, -d), (A, L, -d)], _FLOOR)

def _church(z_bottom=None):
    if z_bottom is None:
        s, zc = '', -_DEP
        for off, h in _PL:
            s += _prism(_cross(_W + off, _E + off), zc, zc + h); zc += h
        s += _prism(_cross(_W, _E), _ZB, 0, _deco)
    else:
        s = _prism(_cross(_W, _E), z_bottom, 0)
    for f in ((.62, .78), (.3, .5)):   # 지붕의 겹친 십자가
        s += _poly([(x, y, 0) for x, y in _cross(_W * f[0], _E * f[1])], 'none', ' fill-opacity="0"')
    return s

def _access():
    L, A, z = _L, _A, -_DEP
    line = lambda pts, extra: f'<polyline points="{_pts(pts)}" fill="none" {extra}/>'
    dash = 'stroke="#fff4dc" stroke-width="1.7" stroke-dasharray="3 3" stroke-linecap="round" stroke-linejoin="round"'
    s = '<g data-s="6">'
    # 바닥의 물 빠지는 도랑(뒷벽을 따라)
    s += _poly([(A + .9, A + .9, z), (L, A + .9, z), (L, A + 1.7, z), (A + 1.7, A + 1.7, z), (A + 1.7, L, z), (A + .9, L, z)], '#4e3127')
    s += line([(L, A + 1.3, z), (A + 1.3, A + 1.3, z), (A + 1.3, L, z)], 'stroke="#7fa7bf" stroke-width="1.1" stroke-linecap="round"')
    # 들어가는 길: 위가 열린 깊은 바위 도랑 → 굴(바위 밑) → 마당 벽의 굴 입구 → 마당 바닥 → 문 앞
    y0, y1, xe = 15.5, 17.5, 4.5
    op = [(0, y0, 0), (xe, y0, 0), (xe, y1, 0), (0, y1, 0)]
    s += _poly(op, '#3a2219') + f'<clipPath id="llTr"><polygon points="{_pts(op)}"/></clipPath>'
    s += '<g clip-path="url(#llTr)">' + _poly([(0, y0, 0), (xe, y0, 0), (xe, y0, -_DEP), (0, y0, -_DEP)], '#7e4b3a') + '</g>'
    ym = (y0 + y1) / 2
    s += _poly([(A, y0, z), (A, y1, z), (A, y1, z + 2.4), (A, y0, z + 2.4)], _HOLE)
    s += line([(.3, ym, 0), (xe, ym, 0)], dash)
    s += line([(xe, ym, 0), (A, ym, z + 1.2)], 'stroke="rgba(255,244,220,.75)" stroke-width="1.3" stroke-dasharray="1 3" stroke-linecap="round"')
    s += line([(A + .2, ym, z), (A + 2.1, L - 1.6, z), (_CX, L - 1.6, z)], dash)
    return s + '</g>'

def _depth_label():
    x1, y1 = _P(_L, _A, 0); x2, y2 = _P(_L, _A, -_DEP); dx = 9
    s = f'<g data-s="3"><line x1="{x1 + dx:.1f}" y1="{y1:.1f}" x2="{x2 + dx:.1f}" y2="{y2:.1f}" stroke="#fff4dc" stroke-width="1.2"/>'
    s += ''.join(f'<line x1="{x1 + dx - 3:.1f}" y1="{yy:.1f}" x2="{x1 + dx + 3:.1f}" y2="{yy:.1f}" stroke="#fff4dc" stroke-width="1.2"/>' for yy in (y1, y2))
    s += (f'<text x="{x1 + dx + 5:.1f}" y="{(y1 + y2) / 2 + 4:.1f}" font-size="11" font-weight="700" fill="#fff4dc" '
          f'stroke="rgba(50,24,14,.55)" stroke-width="2.4" paint-order="stroke" font-family="sans-serif">약 11m</text></g>')
    return s

def _steps_svg():
    L = _L
    ps = [_P(*p) for p in [(0, 0, 0), (L, 0, 0), (0, L, 0), (L, L, 0), (L, 0, -_SLAB), (0, L, -_SLAB), (L, L, -_SLAB)]]
    w = max(a for a, _ in ps) + 16; h = max(b for _, b in ps) + 10
    s = f'<svg viewBox="0 0 {w:.0f} {h:.0f}" xmlns="http://www.w3.org/2000/svg">'
    s += ('<g data-off="2">' + _poly([(L, 0, 0), (L, L, 0), (L, L, -_SLAB), (L, 0, -_SLAB)], _CUTX)
          + _poly([(0, L, 0), (L, L, 0), (L, L, -_SLAB), (0, L, -_SLAB)], _CUTY) + _poly([(0, 0, 0), (L, 0, 0), (L, L, 0), (0, L, 0)], _TOP) + '</g>')
    s += (f'<g data-s="1" data-off="2"><polygon points="{_pts([(x, y, 0) for x, y in _cross(_W, _E)])}" fill="rgba(255,244,220,.16)" '
          'stroke="#fff4dc" stroke-width="2" stroke-dasharray="4 3" stroke-linejoin="round"/></g>')
    s += '<g data-s="2" data-off="3">' + _pit(4.0) + _church(-4.0) + '</g>'
    s += '<g data-s="3">' + _pit(_DEP) + _access() + _church() + '</g>'
    return s + _depth_label() + '</svg>'

