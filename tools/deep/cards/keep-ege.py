def make_four(src_dir):
    """네 낱장을 두 줄로 나란히 놓은 그림(1800×2560)을 deep_src/keep-ege/beauvais_four_leaves.jpg로 만들어요.
    칸 비율 0.69(낱장의 실제 비율 290×204mm에 가깝게) · 왼쪽 위 클리블랜드(위쪽만) · 오른쪽 위 보스턴 1 · 왼쪽 아래 보스턴 2 · 오른쪽 아래 필라델피아.
    빌드할 때는 부르지 않아요(그림은 이미 만들어 두었어요)."""
    import os
    from PIL import Image, ImageFilter, ImageDraw
    W, H, g = 1800, 2560, 36
    cw, ch = (W - 3 * g) // 2, (H - 3 * g) // 2
    cells = [(F_CMA, CROP_CMA, (g, g)), (F_BPL1, CROP_BPL1, (2 * g + cw, g)),
             (F_BPL3, CROP_BPL3, (g, 2 * g + ch)), (F_TEM, CROP_TEM, (2 * g + cw, 2 * g + ch))]
    bg = Image.new('RGB', (W, H), (214, 203, 184)); sh = Image.new('L', (W, H), 0); sd = ImageDraw.Draw(sh); put = []
    for f, b, (cx, cy) in cells:
        im = Image.open(os.path.join(src_dir, f)).convert('RGB'); w0, h0 = im.size
        c = im.crop((int(b[0] * w0), int(b[1] * h0), int(b[2] * w0), int(b[3] * h0)))
        s = min(cw / c.width, ch / c.height); c = c.resize((int(c.width * s), int(c.height * s)), Image.LANCZOS)
        ox, oy = cx + (cw - c.width) // 2, cy + (ch - c.height) // 2; put.append((c, ox, oy))
        sd.rectangle((ox + 10, oy + 14, ox + c.width + 10, oy + c.height + 14), fill=120)
    bg = Image.composite(Image.new('RGB', (W, H), (60, 48, 36)), bg, sh.filter(ImageFilter.GaussianBlur(14)))
    for c, ox, oy in put: bg.paste(c, (ox, oy))
    bg.save(os.path.join(src_dir, 'beauvais_four_leaves.jpg'), quality=92)

