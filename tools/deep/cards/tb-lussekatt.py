def _spiral(cx, cy, r0, th0, turns=1.12, shrink=.74, n=90):
    pts = []
    tot = 2 * math.pi * turns
    for i in range(n + 1):
        s = tot * i / n
        r = r0 * (1 - shrink * s / tot)
        th = th0 - s
        pts.append((cx + r * math.cos(th), cy + r * math.sin(th)))
    return 'M' + ' L'.join(f'{x:.1f} {y:.1f}' for x, y in pts)


