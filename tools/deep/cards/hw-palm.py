# 바탕: 트윙클 ‘Palm Cross Craft Instructions’(셰필드 세인트존스 랜무어 교회가 나눈 자료)의 10단계를 7단계로 묶었어요.
# 손 모양은 단순하게 줄였어요. 점선은 뒤로 넘어간 부분, 연한 빨간 화살표는 방금 한 손놀림이에요.
EDGE, LEAF, RIB = '#5c8735', '#97c463', '#77a648'
CX, CY = 150, 140          # 십자가 한가운데
W = 14                     # 잎 너비
def strip(x1, y1, x2, y2, cap='butt'):
    return (f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{EDGE}" stroke-width="{W}" stroke-linecap="{cap}"/>'
            f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{LEAF}" stroke-width="{W - 3}" stroke-linecap="{cap}"/>'
            f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{RIB}" stroke-width="1.2"/>')
def loop(x1, y1, x2, y2):
    """접어 겹친 띠(팔·윗동): 끝이 둥글게 꺾여요. 겹친 두 겹을 가는 선으로 보여요."""
    s = strip(x1, y1, x2, y2, 'round')
    if y1 == y2:
        s += f'<line x1="{x1}" y1="{y1 - 2.5}" x2="{x2}" y2="{y2 - 2.5}" stroke="{EDGE}" stroke-width=".8" opacity=".7"/>'
    else:
        s += f'<line x1="{x1 - 2.5}" y1="{y1}" x2="{x2 - 2.5}" y2="{y2}" stroke="{EDGE}" stroke-width=".8" opacity=".7"/>'
    return s
def tip(x, y, d):
    h = W / 2
    pts = {'r': f'{x},{y - h} {x + 18},{y} {x},{y + h}', 'u': f'{x - h},{y} {x},{y - 18} {x + h},{y}',
           'd': f'{x - h},{y} {x},{y + 18} {x + h},{y}'}[d]
    return f'<polygon points="{pts}" fill="{LEAF}" stroke="{EDGE}" stroke-width="1.5" stroke-linejoin="round"/>'
def knot():
    a, b = CX - 11, CY - 11
    return (f'<rect x="{a}" y="{b}" width="22" height="22" rx="2" fill="#7fae4c" stroke="#4b7428" stroke-width="1.6"/>'
            f'<line x1="{a + 2}" y1="{b + 7.5}" x2="{a + 20}" y2="{b + 7.5}" stroke="#4b7428" stroke-width="1"/>'
            f'<line x1="{a + 2}" y1="{b + 14.5}" x2="{a + 20}" y2="{b + 14.5}" stroke="#4b7428" stroke-width="1"/>')
def behind(x1, y1, x2, y2):
    """뒤로 넘어간 부분: 점선 테두리만(세로 띠)."""
    return (f'<rect x="{x1 - W / 2}" y="{y1}" width="{W}" height="{y2 - y1}" rx="6" fill="rgba(151,196,99,.18)" '
            f'stroke="{EDGE}" stroke-width="1.6" stroke-dasharray="3 2.5"/>')
def arrow(d):
    return (f'<path d="{d}" fill="none" stroke="#c0503f" stroke-width="2.2" stroke-linecap="round" opacity=".7" '
            f'marker-end="url(#pcA)"/>')
def palm_svg():
    g = []
    # 0: 긴 잎 한 장(1단계까지 보여요)
    g.append(f'<g data-off="2">{strip(18, CY, 262, CY)}{tip(262, CY, "r")}</g>')
    # 1: 반으로 접었다 편 자국
    g.append(f'<g data-s="1" data-off="2"><line x1="{CX}" y1="{CY - 13}" x2="{CX}" y2="{CY + 13}" stroke="#7a5c2e" '
             f'stroke-width="1.6" stroke-dasharray="3 2.5"/>{arrow("M240 118 Q150 70 64 116")}</g>')
    # 2: 직각으로 세우기
    g.append(f'<g data-s="2" data-off="3">{strip(18, CY, CX + 7, CY)}{strip(CX, CY + 7, CX, 26)}{tip(CX, 26, "u")}'
             f'<line x1="{CX - 7}" y1="{CY + 7}" x2="{CX + 7}" y2="{CY - 7}" stroke="#4b7428" stroke-width="1.2"/>'
             f'{arrow("M246 128 Q236 52 166 40")}</g>')
    # 3: 뒤로 감았다 올려 가운데 네모
    g.append(f'<g data-s="3" data-off="4">{behind(CX, CY + 11, CX, CY + 30)}{strip(18, CY, CX - 11, CY)}'
             f'{strip(CX, CY - 11, CX, 26)}{tip(CX, 26, "u")}{knot()}{arrow("M176 124 Q198 148 176 168")}</g>')
    # 4: 왼쪽 띠를 넘겨 네모 사이로 빼기 → 오른쪽에 긴 고리, 왼쪽으로 끝
    g.append(f'<g data-s="4" data-off="5">{loop(CX + 11, CY, 244, CY)}{strip(30, CY, CX - 11, CY)}'
             f'{strip(CX, CY - 11, CX, 26)}{tip(CX, 26, "u")}{knot()}{arrow("M96 120 Q150 86 214 120")}</g>')
    # 5: 윗동과 기둥
    g.append(f'<g data-s="5" data-off="6">{loop(CX + 11, CY, 244, CY)}{strip(30, CY, CX - 11, CY)}'
             f'{loop(CX, CY - 11, CX, 104)}{strip(CX, CY + 11, CX, 296)}{tip(CX, 296, "d")}{knot()}'
             f'{arrow("M126 92 Q118 150 134 196")}</g>')
    # 6: 왼팔
    g.append(f'<g data-s="6" data-off="7">{loop(CX + 11, CY, 244, CY)}{loop(92, CY, CX - 11, CY)}'
             f'{loop(CX, CY - 11, CX, 104)}{strip(CX, CY + 11, CX, 296)}{tip(CX, 296, "d")}{knot()}'
             f'{arrow("M70 122 Q56 140 76 160")}</g>')
    # 7: 오른팔 — 다 됐어요
    g.append(f'<g data-s="7">{loop(CX + 11, CY, 208, CY)}{loop(92, CY, CX - 11, CY)}'
             f'{loop(CX, CY - 11, CX, 104)}{strip(CX, CY + 11, CX, 296)}{tip(CX, 296, "d")}{knot()}</g>')
    return ('<svg viewBox="0 0 300 330" xmlns="http://www.w3.org/2000/svg">'
            '<defs><marker id="pcA" viewBox="0 0 10 10" refX="7" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse">'
            '<path d="M0 0 L10 5 L0 10 z" fill="#c0503f" opacity=".8"/></marker></defs>'
            '<rect x="5" y="5" width="290" height="320" rx="14" fill="#f4ecd9" stroke="rgba(90,70,30,.2)"/>'
            '<ellipse cx="150" cy="306" rx="96" ry="7" fill="rgba(70,48,14,.10)"/>'
            + ''.join(g) + '</svg>')

