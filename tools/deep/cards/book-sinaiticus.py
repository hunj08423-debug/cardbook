def draw_leaf(path, seed=350):
    """이 안내서가 그린 네 단짜리 낱장(흩어진 조각 모으기용 빗댄 그림). 쪽 모양(네 단·단마다 48줄)만 시나이 사본을 따랐고,
    글자는 그리스 대문자를 흉내 낸 획이에요(실제 글이 아니에요). 원본 폴더에 그림이 없을 때만 다시 그려요."""
    from PIL import Image, ImageDraw, ImageFilter
    R = random.Random(seed)
    k = 2
    W, H = 1500 * k, 1652 * k
    im = Image.new('RGB', (W, H), (232, 217, 184))
    vign = Image.new('L', (W // 20, H // 20), 0); vp = vign.load()
    for y in range(H // 20):
        for x in range(W // 20):
            dx = (x / (W / 20) - .5) * 2; dy = (y / (H / 20) - .5) * 2
            dd = min(1, (dx * dx * .9 + dy * dy * .8) ** .5)
            vp[x, y] = int(max(0, dd - .45) / .55 * 70)
    vign = vign.resize((W, H), Image.BICUBIC).filter(ImageFilter.GaussianBlur(40))
    im = Image.composite(Image.new('RGB', (W, H), (196, 172, 128)), im, vign)
    blot = Image.new('L', (W // 40, H // 40), 0); bp = blot.load()
    for y in range(H // 40):
        for x in range(W // 40):
            bp[x, y] = R.randint(0, 26)
    blot = blot.resize((W, H), Image.BICUBIC).filter(ImageFilter.GaussianBlur(30))
    im = Image.composite(Image.new('RGB', (W, H), (214, 196, 158)), im, blot)
    d = ImageDraw.Draw(im)
    for _ in range(900):
        x, y = R.randint(0, W), R.randint(0, H); r = R.choice((1, 1, 2)) * k
        d.ellipse([x - r, y - r, x + r, y + r], fill=(205, 186, 150))
    top, bot = .09 * H, .91 * H
    cols = [(.08 + i * (.19 + .1 / 3)) for i in range(4)]
    cw = .19 * W; n = 48; lh = (bot - top) / n
    for c in cols:
        x0 = c * W
        d.line([(x0, top - lh * .6), (x0, bot)], fill=(214, 198, 166), width=k)
        d.line([(x0 + cw, top - lh * .6), (x0 + cw, bot)], fill=(214, 198, 166), width=k)
        for i in range(n):
            y = top + (i + 1) * lh - lh * .22
            d.line([(x0, y), (x0 + cw, y)], fill=(220, 205, 175), width=k)
    gh = lh * .56; sw = int(2.3 * k)
    def glyph(x, y, w, kind, col):
        t, b, m = y - gh, y, y - gh / 2
        L = lambda *pts: d.line(list(pts), fill=col, width=sw)
        if kind == 'O': d.ellipse([x, t, x + w, b], outline=col, width=sw)
        elif kind == 'C': d.arc([x, t, x + w * 1.1, b], 50, 310, fill=col, width=sw)
        elif kind == 'E': d.arc([x, t, x + w * 1.1, b], 50, 310, fill=col, width=sw); L((x + sw, m), (x + w * .75, m))
        elif kind == 'I': L((x + w * .5, t), (x + w * .5, b))
        elif kind == 'N': L((x, t), (x, b)); L((x + w, t), (x + w, b)); L((x, t), (x + w, b))
        elif kind == 'H': L((x, t), (x, b)); L((x + w, t), (x + w, b)); L((x, m), (x + w, m))
        elif kind == 'P': L((x, t), (x, b)); L((x + w, t), (x + w, b)); L((x - sw, t), (x + w + sw, t))
        elif kind == 'T': L((x, t), (x + w, t)); L((x + w / 2, t), (x + w / 2, b))
        elif kind == 'A': L((x, b), (x + w / 2, t)); L((x + w / 2, t), (x + w, b)); L((x + w * .25, m + gh * .1), (x + w * .75, m + gh * .1))
        elif kind == 'L': L((x, b), (x + w / 2, t)); L((x + w / 2, t), (x + w, b))
        elif kind == 'D': L((x, b), (x + w / 2, t)); L((x + w / 2, t), (x + w, b)); L((x - sw, b), (x + w + sw, b))
        elif kind == 'M': L((x, t), (x, b)); L((x + w, t), (x + w, b)); L((x, t), (x + w / 2, m + gh * .2)); L((x + w / 2, m + gh * .2), (x + w, t))
        elif kind == 'Y': L((x, t), (x + w / 2, m)); L((x + w, t), (x + w / 2, m)); L((x + w / 2, m), (x + w / 2, b))
        elif kind == 'K': L((x, t), (x, b)); L((x, m), (x + w, t)); L((x, m), (x + w, b))
        elif kind == 'R': L((x, t), (x, b + gh * .3)); d.arc([x - w * .2, t, x + w * .9, m + gh * .1], 270, 90, fill=col, width=sw)
        elif kind == 'W':
            d.arc([x, t + gh * .2, x + w / 2, b], 0, 180, fill=col, width=sw); d.arc([x + w / 2, t + gh * .2, x + w, b], 0, 180, fill=col, width=sw)
            L((x, t + gh * .2), (x, m)); L((x + w, t + gh * .2), (x + w, m))
    kinds = 'OOCCEEIIINNNHHPPTTAAALLDMYYKRW'
    wid = {'I': .35, 'M': 1.15, 'W': 1.15}
    for c in cols:
        x0 = c * W
        for i in range(n):
            y = top + (i + 1) * lh - lh * .22 - k
            end = x0 + cw - R.uniform(0, lh * .5)
            if R.random() < .05: end = x0 + cw * R.uniform(.35, .8)
            x = x0 + R.uniform(0, 3) * k
            col = (R.randint(58, 76), R.randint(40, 52), R.randint(26, 34))
            while True:
                kd = R.choice(kinds); w = gh * .78 * wid.get(kd, 1)
                if x + w > end: break
                glyph(x, y, w, kd, col)
                x += w + gh * .3
    im.resize((W // k, H // k), Image.LANCZOS).save(path, 'PNG', optimize=True)

